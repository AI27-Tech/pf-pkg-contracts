// Command gen-roles genera el enum de ROLES de AI27 para Go y TypeScript desde
// la fuente única contracts/openapi/_comunes.yaml (esquema `Rol`).
//
// Por qué un generador aparte y no sólo el bundle de OpenAPI: el enum `Rol` es
// un dato de dominio que viaja en el TOKEN, y el token no es parte de la
// superficie HTTP. El enum estaba declarado en `_comunes.yaml` pero ningún spec
// lo `$ref`-eba, así que el bundle lo podaba y `Rol` nunca llegaba a los
// clientes generados: el contrato declaraba ocho (ahora) roles que ningún
// consumidor Go o TS podía nombrar sin escribir el enum a mano. Eso contradice el
// criterio de E0-T2.
//
// La salida vive en su propio paquete (`roles`) y NO se referencia desde los
// specs: si un spec hiciera `$ref` a `Rol`, el mismo enum aparecería dos veces
// (aquí y en el cliente del servicio) y volverían a divergir. La regla es: los
// servicios importan el enum de `roles`, nunca de su propio cliente.
//
// Decisión de diseño que este archivo deja explícita y que conviene no perder de
// vista: el token lleva identidad, tenant, `rol` y `Audiencia`; el ALCANCE no
// viaja en el token, se resuelve en servidor. Y `Audiencia` es un valor de
// dominio DISTINTO del claim técnico `aud` del JWT: mapea `cliente` a `Cliente`
// y los otros siete roles a `Interno`.
//
// Uso:
//
//	go run ./tools/gen-roles \
//	    -src contracts/openapi/_comunes.yaml \
//	    -go  packages/api-client-go/roles/roles.gen.go \
//	    -ts  packages/api-client-ts/src/roles/roles.gen.ts
//
// La generación es reproducible: el mismo commit y toolchain producen los mismos
// bytes de salida (ADR 25: codegen reproducible).
//
// Convenciones (ADR 22 / DEC-024): los identificadores técnicos van en inglés,
// pero los roles son sustantivos de dominio y conservan su forma canónica en
// español. El generador NO traduce ni renombra ningún rol.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

// source es el recorte mínimo de _comunes.yaml que este generador necesita. Los
// componentes que no se usan se ignoran.
type source struct {
	Components struct {
		Schemas map[string]struct {
			Type        string   `yaml:"type"`
			Description string   `yaml:"description"`
			Enum        []string `yaml:"enum"`
		} `yaml:"schemas"`
	} `yaml:"components"`
}

// nombreEsquema es la clave del enum dentro de _comunes.yaml.
const nombreEsquema = "Rol"

func main() {
	src := flag.String("src", "contracts/openapi/_comunes.yaml", "ruta de la fuente YAML")
	goOut := flag.String("go", "", "ruta de salida Go")
	tsOut := flag.String("ts", "", "ruta de salida TypeScript")
	flag.Parse()

	raw, err := os.ReadFile(*src)
	if err != nil {
		fatal("no se pudo leer la fuente: %v", err)
	}
	var s source
	if err := yaml.Unmarshal(raw, &s); err != nil {
		fatal("YAML inválido: %v", err)
	}

	rol, ok := s.Components.Schemas[nombreEsquema]
	if !ok {
		fatal("no se encontró el esquema %q en la fuente", nombreEsquema)
	}
	if rol.Type != "" && rol.Type != "string" {
		fatal("el esquema %q debe ser de tipo string, es %q", nombreEsquema, rol.Type)
	}
	if len(rol.Enum) == 0 {
		fatal("el esquema %q no declara enum", nombreEsquema)
	}
	if err := validar(rol.Enum); err != nil {
		fatal("enum de roles inconsistente: %v", err)
	}

	if *goOut != "" {
		formatted, err := format.Source(genGo(rol.Enum))
		if err != nil {
			fatal("gofmt del Go generado: %v", err)
		}
		if err := writeFile(*goOut, formatted); err != nil {
			fatal("escribir Go: %v", err)
		}
		fmt.Fprintf(os.Stderr, "gen-roles: escrito %s (%d roles)\n", *goOut, len(rol.Enum))
	}
	if *tsOut != "" {
		if err := writeFile(*tsOut, genTS(rol.Enum)); err != nil {
			fatal("escribir TS: %v", err)
		}
		fmt.Fprintf(os.Stderr, "gen-roles: escrito %s (%d roles)\n", *tsOut, len(rol.Enum))
	}
}

// validar comprueba que el enum sea utilizable como fuente: identificadores
// únicos y no vacíos, en forma snake_case (que es la forma canónica que viaja en
// el claim `rol`).
func validar(enum []string) error {
	vistos := map[string]bool{}
	for _, r := range enum {
		switch {
		case r == "":
			return fmt.Errorf("rol vacío")
		case r != strings.ToLower(r):
			return fmt.Errorf("rol %q no está en minúsculas; la forma canónica del claim `rol` es snake_case", r)
		case strings.ContainsAny(r, " -"):
			return fmt.Errorf("rol %q no puede contener espacios ni guiones", r)
		case vistos[r]:
			return fmt.Errorf("rol duplicado: %s", r)
		}
		vistos[r] = true
	}
	return nil
}

func genGo(enum []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-roles. DO NOT EDIT.\n")
	b.WriteString("// Fuente: contracts/openapi/_comunes.yaml, esquema Rol.\n")
	b.WriteString("//\n")
	b.WriteString("// El enum vive aquí y no en el cliente de cada servicio a propósito: es\n")
	b.WriteString("// un dato de dominio que viaja en el TOKEN, no en la superficie HTTP. Los\n")
	b.WriteString("// servicios importan este paquete.\n\n")
	b.WriteString("package roles\n\n")

	b.WriteString("// Rol es el rol del sujeto dentro del tenant. El token lleva identidad,\n")
	b.WriteString("// tenant, `rol` y `Audiencia`; el ALCANCE NO viaja en el token, se resuelve\n")
	b.WriteString("// en servidor. `Audiencia` es un valor de dominio distinto del claim técnico\n")
	b.WriteString("// `aud` del JWT: mapea el rol `cliente` a `Cliente` y los otros siete a\n")
	b.WriteString("// `Interno`.\n")
	b.WriteString("type Rol string\n\n")

	b.WriteString("const (\n")
	for _, r := range enum {
		fmt.Fprintf(&b, "\tRol%s Rol = %q\n", camel(r), r)
	}
	b.WriteString(")\n\n")

	b.WriteString("// Todos son los roles canónicos del contrato, en el orden de la fuente.\n")
	b.WriteString("var Todos = []Rol{\n")
	for _, r := range enum {
		fmt.Fprintf(&b, "\tRol%s,\n", camel(r))
	}
	b.WriteString("}\n\n")

	b.WriteString("// EsRol indica si el valor es un rol del contrato. Un rol desconocido se\n")
	b.WriteString("// rechaza en servidor; nunca se degrada a un permiso por defecto.\n")
	b.WriteString("func EsRol(v string) bool {\n\tswitch Rol(v) {\n")
	b.WriteString("\tcase ")
	casos := make([]string, len(enum))
	for i, r := range enum {
		casos[i] = "Rol" + camel(r)
	}
	b.WriteString(strings.Join(casos, ", "))
	b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")

	b.WriteString("// EsInterno indica si el rol pertenece a la superficie interna del producto.\n")
	b.WriteString("// `cliente` es el único externo; los otros siete son internos.\n")
	fmt.Fprintf(&b, "func (r Rol) EsInterno() bool {\n\treturn r != Rol%s\n}\n", camel(primerNoCliente(enum)))

	return b.Bytes()
}

func genTS(enum []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-roles. DO NOT EDIT.\n")
	b.WriteString("// Fuente: contracts/openapi/_comunes.yaml, esquema Rol.\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * El rol del sujeto dentro del tenant. El token lleva identidad, tenant,\n")
	b.WriteString(" * `rol` y `Audiencia`; el ALCANCE NO viaja en el token, se resuelve en\n")
	b.WriteString(" * servidor. `Audiencia` es un valor de dominio distinto del claim técnico\n")
	b.WriteString(" * `aud` del JWT.\n")
	b.WriteString(" */\n")
	b.WriteString("export const Rol = {\n")
	for _, r := range enum {
		fmt.Fprintf(&b, "  %s: %q,\n", camel(r), r)
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type Rol = (typeof Rol)[keyof typeof Rol];\n\n")

	b.WriteString("/** Todos los roles canónicos, en el orden de la fuente. */\n")
	b.WriteString("export const ROLES: readonly Rol[] = [\n")
	for _, r := range enum {
		fmt.Fprintf(&b, "  Rol.%s,\n", camel(r))
	}
	b.WriteString("];\n\n")

	b.WriteString("/** Un rol desconocido se rechaza en servidor; nunca degrada a un permiso. */\n")
	b.WriteString("export function esRol(v: string): v is Rol {\n")
	b.WriteString("  return (ROLES as readonly string[]).includes(v);\n}\n\n")

	b.WriteString("/** `cliente` es el único rol externo; los otros siete son internos. */\n")
	b.WriteString("export function esInterno(r: Rol): boolean {\n")
	fmt.Fprintf(&b, "  return r !== Rol.%s;\n}\n", camel(primerNoCliente(enum)))

	return b.Bytes()
}

// primerNoCliente devuelve el primer rol que no es `cliente`: el único rol
// externo. Si el enum dejara de contener `cliente`, devuelve el primero, que es
// lo menos asertivo posible para un generador que no puede inventar semántica.
func primerNoCliente(enum []string) string {
	for _, r := range enum {
		if r != "cliente" {
			return r
		}
	}
	return ""
}

// camel convierte un rol snake_case a su forma PascalCase en Go y TypeScript:
// jefe_operativo -> JefeOperativo, administrador -> Administrador.
func camel(token string) string {
	parts := strings.Split(strings.ToLower(token), "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

func dir(path string) string {
	if i := strings.LastIndex(path, "/"); i >= 0 {
		return path[:i]
	}
	return "."
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-roles: "+format+"\n", args...)
	os.Exit(1)
}
