// Command gen-registro genera el REGISTRO CONTRACTUAL DE TIPOS DE EVENTO para Go
// y TypeScript desde la fuente única contracts/events/registro.tipos.yaml.
//
// Antes de tracer.2 el registro de tipos sólo existía como prosa en
// INVENTARIO.md. Eso no es un registro: ninguna herramienta podía leerlo, y el
// fanout no tenía forma de validar el campo `tipo` del Sobre contra una fuente.
// Este generador convierte esa prosa en dato generado, por el mismo camino que
// el resto del codegen (scripts/generar.sh), de modo que Go y TS digan lo mismo
// que la fuente y que INVENTARIO.md.
//
// Uso:
//
//	go run ./tools/gen-registro \
//	    -src contracts/events/registro.tipos.yaml \
//	    -go  packages/api-client-go/registro/registro.gen.go \
//	    -ts  packages/api-client-ts/src/registro/registro.gen.ts
//
// La generación es reproducible: el mismo commit y toolchain producen los mismos
// bytes de salida (ADR 25: codegen reproducible).
//
// Convenciones (ADR 22 / DEC-024): los nombres de evento son sustantivos de
// dominio y conservan su forma canónica en español (`viaje.estado_cambiado`).
// El generador NO traduce ni normaliza esos nombres.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"

	"gopkg.in/yaml.v3"
)

// tipoEvento es una fila del registro: exactamente las columnas que fija
// INVENTARIO.md.
type tipoEvento struct {
	Tipo                 string   `yaml:"tipo"`
	Version              uint32   `yaml:"version"`
	Productor            string   `yaml:"productor"`
	ConsumidoresDurables []string `yaml:"consumidores_durables"`
	Agregado             string   `yaml:"agregado"`
	Sensibilidad         string   `yaml:"sensibilidad"`
}

type source struct {
	Version        int         `yaml:"version"`
	Tipos          []tipoEvento `yaml:"tipos"`
	FueraDelTracer [][]string  `yaml:"fuera_del_tracer"`
}

// Sensibilidades válidas. `amplia` es la única del tracer; `restringida` existe
// para que una release posterior la use de forma explícita y no por omisión.
const (
	sensibilidadAmplia      = "amplia"
	sensibilidadRestringida = "restringida"
)

func main() {
	src := flag.String("src", "contracts/events/registro.tipos.yaml", "ruta de la fuente YAML")
	goOut := flag.String("go", "", "ruta de salida Go")
	tsOut := flag.String("ts", "", "ruta de salida TypeScript")
	flag.Parse()

	raw, err := os.ReadFile(*src)
	if err != nil {
		fatal("no se pudo leer la fuente: %v", err)
	}
	var s source
	if err := yaml.Unmarshal(raw, &s); err != nil {
		fatal("YAML inválido: %v", err)
	}
	if err := validate(&s); err != nil {
		fatal("registro inconsistente: %v", err)
	}

	if *goOut != "" {
		formatted, err := format.Source(genGo(&s))
		if err != nil {
			fatal("gofmt del Go generado: %v", err)
		}
		if err := writeFile(*goOut, formatted); err != nil {
			fatal("escribir Go: %v", err)
		}
		fmt.Fprintf(os.Stderr, "gen-registro: escrito %s (%d tipos)\n", *goOut, len(s.Tipos))
	}
	if *tsOut != "" {
		if err := writeFile(*tsOut, genTS(&s)); err != nil {
			fatal("escribir TS: %v", err)
		}
		fmt.Fprintf(os.Stderr, "gen-registro: escrito %s (%d tipos)\n", *tsOut, len(s.Tipos))
	}
}

// validate comprueba las invariantes del registro. Un registro con tipos
// duplicados, sin productor, o con una sensibilidad desconocida no es una fuente
// válida: el fanout no podría interpretarlo.
func validate(s *source) error {
	if s.Version != 1 {
		return fmt.Errorf("versión de registro no soportada: %d (se espera 1)", s.Version)
	}
	vistos := map[string]bool{}
	for _, t := range s.Tipos {
		switch {
		case t.Tipo == "":
			return fmt.Errorf("tipo sin nombre")
		case t.Productor == "":
			return fmt.Errorf("%s: sin productor", t.Tipo)
		case t.Agregado == "":
			return fmt.Errorf("%s: sin agregado (la clave de orden es obligatoria, ADR 29)", t.Tipo)
		case t.Version == 0:
			return fmt.Errorf("%s: versión 0", t.Tipo)
		case len(t.ConsumidoresDurables) == 0:
			return fmt.Errorf("%s: sin consumidores durables", t.Tipo)
		}
		switch t.Sensibilidad {
		case sensibilidadAmplia, sensibilidadRestringida:
		default:
			return fmt.Errorf("%s: sensibilidad desconocida %q", t.Tipo, t.Sensibilidad)
		}
		if vistos[t.Tipo] {
			return fmt.Errorf("tipo duplicado: %s", t.Tipo)
		}
		vistos[t.Tipo] = true
	}
	return nil
}

func genGo(s *source) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-registro. DO NOT EDIT.\n")
	b.WriteString("// Fuente: contracts/events/registro.tipos.yaml (C5, handoff tracer.2).\n\n")
	b.WriteString("package registro\n\n")

	b.WriteString("// Sensibilidad es la superficie de datos que el evento expone (ADR 20).\n")
	b.WriteString("type Sensibilidad string\n\n")
	b.WriteString("const (\n")
	fmt.Fprintf(&b, "\tSensibilidadAmplia Sensibilidad = %q\n", sensibilidadAmplia)
	fmt.Fprintf(&b, "\tSensibilidadRestringida Sensibilidad = %q\n", sensibilidadRestringida)
	b.WriteString(")\n\n")

	b.WriteString("// TipoEvento es una entrada del registro contractual de tipos de evento.\n")
	b.WriteString("//\n")
	b.WriteString("// Tipo es el valor del campo `tipo` del Sobre. El campo Version es la\n")
	b.WriteString("// versión del contrato de SU payload; no la del Sobre.\n")
	b.WriteString("type TipoEvento struct {\n")
	b.WriteString("\tTipo                 string\n")
	b.WriteString("\tVersion              uint32\n")
	b.WriteString("\tProductor            string\n")
	b.WriteString("\tConsumidoresDurables []string\n")
	b.WriteString("\tAgregado             string\n")
	b.WriteString("\tSensibilidad         Sensibilidad\n")
	b.WriteString("}\n\n")

	b.WriteString("// Tipos es el registro completo, en el orden de la fuente.\n")
	b.WriteString("// Generado desde la fuente; no se edita a mano.\n")
	b.WriteString("var Tipos = []TipoEvento{\n")
	for _, t := range s.Tipos {
		b.WriteString("\t{\n")
		fmt.Fprintf(&b, "\t\tTipo:                 %q,\n", t.Tipo)
		fmt.Fprintf(&b, "\t\tVersion:              %d,\n", t.Version)
		fmt.Fprintf(&b, "\t\tProductor:            %q,\n", t.Productor)
		fmt.Fprintf(&b, "\t\tConsumidoresDurables: []string{%s},\n", goStrings(t.ConsumidoresDurables))
		fmt.Fprintf(&b, "\t\tAgregado:             %q,\n", t.Agregado)
		fmt.Fprintf(&b, "\t\tSensibilidad:         Sensibilidad%s,\n", goConst(t.Sensibilidad))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// PorTipo indexa el registro por nombre de tipo.\n")
	b.WriteString("var PorTipo = func() map[string]TipoEvento {\n")
	b.WriteString("\tm := make(map[string]TipoEvento, len(Tipos))\n")
	b.WriteString("\tfor _, t := range Tipos {\n\t\tm[t.Tipo] = t\n\t}\n")
	b.WriteString("\treturn m\n}()\n\n")

	b.WriteString("// EsTipoRegistrado indica si el tipo está en el registro. Un tipo no registrado\n")
	b.WriteString("// se rechaza ANTES del fanout; si llega a un consumidor, es un evento\n")
	b.WriteString("// venenoso (ver INVENTARIO.md).\n")
	b.WriteString("func EsTipoRegistrado(tipo string) bool {\n")
	b.WriteString("\t_, ok := PorTipo[tipo]\n\treturn ok\n}\n\n")

	b.WriteString("// VersionDe devuelve la versión de contrato del payload de un tipo registrado.\n")
	b.WriteString("// ok es false si el tipo no está en el registro.\n")
	b.WriteString("func VersionDe(tipo string) (uint32, bool) {\n")
	b.WriteString("\tt, ok := PorTipo[tipo]\n\tif !ok {\n\t\treturn 0, false\n\t}\n\treturn t.Version, true\n}\n\n")

	b.WriteString("// ProductorDe devuelve el servicio que publica el tipo, y ok=false si el tipo\n")
	b.WriteString("// no está en el registro.\n")
	b.WriteString("func ProductorDe(tipo string) (string, bool) {\n")
	b.WriteString("\tt, ok := PorTipo[tipo]\n\tif !ok {\n\t\treturn \"\", false\n\t}\n\treturn t.Productor, true\n}\n\n")

	b.WriteString("// EsConsumidorDurable indica si el servicio-consumer conserva una proyección\n")
	b.WriteString("// durable del tipo. Un consumidor que no aparece en la lista no debe\n")
	b.WriteString("// demonizar.\n")
	b.WriteString("func EsConsumidorDurable(tipo, consumidor string) bool {\n")
	b.WriteString("\tt, ok := PorTipo[tipo]\n\tif !ok {\n\t\treturn false\n\t}\n")
	b.WriteString("\tfor _, c := range t.ConsumidoresDurables {\n")
	b.WriteString("\t\tif c == consumidor {\n\t\t\treturn true\n\t\t}\n\t}\n\treturn false\n}\n")

	return b.Bytes()
}

func genTS(s *source) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-registro. DO NOT EDIT.\n")
	b.WriteString("// Fuente: contracts/events/registro.tipos.yaml (C5, handoff tracer.2).\n\n")

	b.WriteString("/** Superficie de datos que el evento expone (ADR 20). */\n")
	b.WriteString("export const Sensibilidad = {\n")
	fmt.Fprintf(&b, "  Amplia: %q,\n", sensibilidadAmplia)
	fmt.Fprintf(&b, "  Restringida: %q,\n", sensibilidadRestringida)
	b.WriteString("} as const;\n\n")
	b.WriteString("export type Sensibilidad = (typeof Sensibilidad)[keyof typeof Sensibilidad];\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Entrada del registro contractual de tipos de evento.\n")
	b.WriteString(" *\n")
	b.WriteString(" * `tipo` es el valor del campo `tipo` del Sobre; `version` es la versión del\n")
	b.WriteString(" * contrato de SU payload, no la del Sobre.\n")
	b.WriteString(" */\n")
	b.WriteString("export interface TipoEvento {\n")
	b.WriteString("  readonly tipo: string;\n")
	b.WriteString("  readonly version: number;\n")
	b.WriteString("  readonly productor: string;\n")
	b.WriteString("  readonly consumidoresDurables: readonly string[];\n")
	b.WriteString("  readonly agregado: string;\n")
	b.WriteString("  readonly sensibilidad: Sensibilidad;\n")
	b.WriteString("}\n\n")

	b.WriteString("/** Registro completo, en el orden de la fuente. */\n")
	b.WriteString("export const TIPOS_EVENTO: readonly TipoEvento[] = [\n")
	for _, t := range s.Tipos {
		b.WriteString("  {\n")
		fmt.Fprintf(&b, "    tipo: %q,\n", t.Tipo)
		fmt.Fprintf(&b, "    version: %d,\n", t.Version)
		fmt.Fprintf(&b, "    productor: %q,\n", t.Productor)
		fmt.Fprintf(&b, "    consumidoresDurables: [%s],\n", tsStrings(t.ConsumidoresDurables))
		fmt.Fprintf(&b, "    agregado: %q,\n", t.Agregado)
		fmt.Fprintf(&b, "    sensibilidad: Sensibilidad.%s,\n", tsKey(t.Sensibilidad))
		b.WriteString("  },\n")
	}
	b.WriteString("];\n\n")

	b.WriteString("const porTipo: ReadonlyMap<string, TipoEvento> = new Map(\n")
	b.WriteString("  TIPOS_EVENTO.map((t) => [t.tipo, t] as const),\n")
	b.WriteString(");\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Un tipo no registrado se rechaza ANTES del fanout; si llega a un\n")
	b.WriteString(" * consumidor, es un evento venenoso (ver INVENTARIO.md).\n")
	b.WriteString(" */\n")
	b.WriteString("export function esTipoRegistrado(tipo: string): boolean {\n")
	b.WriteString("  return porTipo.has(tipo);\n}\n\n")

	b.WriteString("/** Versión de contrato del payload, o undefined si el tipo no está registrado. */\n")
	b.WriteString("export function versionDe(tipo: string): number | undefined {\n")
	b.WriteString("  return porTipo.get(tipo)?.version;\n}\n\n")

	b.WriteString("/** Servicio que publica el tipo, o undefined si no está registrado. */\n")
	b.WriteString("export function productorDe(tipo: string): string | undefined {\n")
	b.WriteString("  return porTipo.get(tipo)?.productor;\n}\n\n")

	b.WriteString("/**\n")
	b.WriteString(" * Si el consumidor conserva una proyección durable del tipo. Un consumidor\n")
	b.WriteString(" * que no aparece en la lista no debe demonizar.\n")
	b.WriteString(" */\n")
	b.WriteString("export function esConsumidorDurable(tipo: string, consumidor: string): boolean {\n")
	b.WriteString("  return porTipo.get(tipo)?.consumidoresDurables.includes(consumidor) ?? false;\n}\n")

	return b.Bytes()
}

// goStrings formatea una lista de cadenas como literales Go.
func goStrings(vs []string) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = fmt.Sprintf("%q", v)
	}
	return strings.Join(q, ", ")
}

// tsStrings formatea una lista de cadenas como literales TypeScript.
func tsStrings(vs []string) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = fmt.Sprintf("%q", v)
	}
	return strings.Join(q, ", ")
}

// goConst traduce el token de sensibilidad al sufijo de la constante Go.
func goConst(s string) string {
	switch s {
	case sensibilidadAmplia:
		return "Amplia"
	case sensibilidadRestringida:
		return "Restringida"
	default:
		fatal("sensibilidad desconocida: %q", s)
		return ""
	}
}

// tsKey traduce el token de sensibilidad a la clave del objeto Sensibilidad.
func tsKey(s string) string {
	switch s {
	case sensibilidadAmplia:
		return "Amplia"
	case sensibilidadRestringida:
		return "Restringida"
	default:
		fatal("sensibilidad desconocida: %q", s)
		return ""
	}
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

func dir(path string) string {
	if i := strings.LastIndex(path, "/"); i >= 0 {
		return path[:i]
	}
	return "."
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-registro: "+format+"\n", args...)
	os.Exit(1)
}